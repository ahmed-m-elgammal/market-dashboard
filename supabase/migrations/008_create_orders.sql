-- =============================================================================
-- ORDERS TABLE (P1C-01)
-- Core order record. Every order goes through a defined status flow.
-- Status flow: pending → confirmed → preparing → ready → picked_up → on_the_way → delivered
--              pending → cancelled (customer/driver/admin/system)
--              on_the_way → cancelled (rare, admin only)
-- =============================================================================
CREATE TABLE orders (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Auto-generated order number (ORD-XXXXXX format, generated by trigger)
  order_number TEXT UNIQUE,

  -- Parties
  customer_id UUID NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
  merchant_id UUID NOT NULL REFERENCES merchants(id) ON DELETE CASCADE,
  driver_id UUID REFERENCES profiles(id) ON DELETE SET NULL,

  -- Order status
  status TEXT NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'confirmed', 'preparing', 'ready', 'picked_up', 'on_the_way', 'delivered', 'cancelled')),

  -- Delivery address snapshot (JSONB: {address, lat, lng, building, floor, apartment, landmark, city, area})
  delivery_address JSONB NOT NULL,

  -- Contact phone for this order (may differ from profile phone)
  customer_phone TEXT,

  -- Price breakdown (all in EGP)
  subtotal NUMERIC(10,2) NOT NULL CHECK (subtotal >= 0),
  delivery_fee NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (delivery_fee >= 0),
  platform_fee NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (platform_fee >= 0),
  discount_amount NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
  total NUMERIC(10,2) NOT NULL CHECK (total >= 0),

  -- Payment
  payment_method TEXT NOT NULL DEFAULT 'cash'
    CHECK (payment_method IN ('cash', 'card', 'vodafone_cash', 'instapay', 'orange_cash', 'wallet')),
  payment_status TEXT NOT NULL DEFAULT 'pending'
    CHECK (payment_status IN ('pending', 'pending_cash', 'paid', 'failed', 'refunded', 'pending_refund', 'partial_refund', 'refund_failed')),

  -- Paymob integration
  paymob_order_id TEXT,
  paymob_transaction_id TEXT,

  -- Promo code (if applied)
  -- NOTE: FK to promo_codes added in 011_create_promo_codes.sql (table created there)
  promo_code_id UUID,
  promo_code TEXT,

  -- Distance & delivery info
  distance_km NUMERIC(6,2),
  estimated_delivery_minutes INTEGER,

  -- Cancellation fields (from 23-ORDER-CANCELLATION.md)
  cancelled_by UUID REFERENCES profiles(id),
  cancellation_reason TEXT,
  cancellation_fee NUMERIC(10,2) DEFAULT 0 CHECK (cancellation_fee >= 0),
  cancelled_at TIMESTAMPTZ,

  -- Refund fields
  refund_amount NUMERIC(10,2),
  refunded_at TIMESTAMPTZ,
  refund_id TEXT,
  refund_status TEXT
    CHECK (refund_status IS NULL OR refund_status IN ('pending_refund', 'refunded', 'refund_failed', 'partial_refund')),

  -- Internal admin notes (not visible to customer/driver)
  admin_notes TEXT,

  -- Idempotency key (prevents duplicate orders on retry)
  idempotency_key TEXT UNIQUE,

  -- Merchant commission (snapshot at order time)
  merchant_commission_pct NUMERIC(5,2),
  merchant_payout NUMERIC(10,2) GENERATED ALWAYS AS (
    subtotal - (subtotal * COALESCE(merchant_commission_pct, 0) / 100)
  ) STORED,

  -- Timestamps
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  confirmed_at TIMESTAMPTZ,
  delivered_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =============================================================================
-- ORDER_ITEMS TABLE (P1C-02)
-- Items in an order with PRICE SNAPSHOTS.
-- Critical: Stores item names and prices AT ORDER TIME, not references.
-- This ensures old orders still show correct amounts if merchant changes prices.
-- =============================================================================
CREATE TABLE order_items (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Order reference
  order_id UUID NOT NULL REFERENCES orders(id) ON DELETE CASCADE,

  -- Item reference (for linking back, but snapshot data is used for display)
  item_id UUID NOT NULL REFERENCES items(id) ON DELETE CASCADE,

  -- Price snapshot at order time (CRITICAL: never change these after insert)
  item_name_ar TEXT NOT NULL,
  item_name_en TEXT NOT NULL,
  item_price NUMERIC(10,2) NOT NULL CHECK (item_price >= 0),

  -- Quantity
  quantity INTEGER NOT NULL CHECK (quantity > 0),

  -- Selected options snapshot (JSONB array of selected choices)
  -- Format: [{"option_name_ar": "...", "option_name_en": "...", "choice_name_ar": "...", "choice_name_en": "...", "price_modifier": 5.00}, ...]
  selected_options JSONB NOT NULL DEFAULT '[]'::jsonb,

  -- Total for this line item (item_price + sum of option modifiers) * quantity
  total_price NUMERIC(10,2) NOT NULL CHECK (total_price >= 0),

  -- Special instructions for this item
  special_instructions TEXT,

  -- Timestamp
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =============================================================================
-- ORDER_STATUS_HISTORY TABLE (P1C-03)
-- Audit trail for every order status change.
-- Every status transition is logged with who changed it and why.
-- =============================================================================
CREATE TABLE order_status_history (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),

  -- Order reference
  order_id UUID NOT NULL REFERENCES orders(id) ON DELETE CASCADE,

  -- Status at this point
  status TEXT NOT NULL
    CHECK (status IN ('pending', 'confirmed', 'preparing', 'ready', 'picked_up', 'on_the_way', 'delivered', 'cancelled')),

  -- Who changed the status (UUID of user, or 'system' for auto-cancellations)
  changed_by UUID REFERENCES profiles(id),
  changed_by_role TEXT
    CHECK (changed_by_role IS NULL OR changed_by_role IN ('customer', 'driver', 'admin', 'system')),

  -- Optional note/reason for the change
  note TEXT,

  -- Timestamp
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- =============================================================================
-- INDEXES
-- =============================================================================

-- Orders: by customer (order history screen)
CREATE INDEX idx_orders_customer_created
  ON orders(customer_id, created_at DESC);

-- Orders: by merchant + status (merchant order management)
CREATE INDEX idx_orders_merchant_status_created
  ON orders(merchant_id, status, created_at DESC);

-- Orders: by driver (driver's order history)
CREATE INDEX idx_orders_driver_created
  ON orders(driver_id, created_at DESC) WHERE driver_id IS NOT NULL;

-- Orders: active orders (for admin dashboard, driver tracking)
CREATE INDEX idx_orders_active
  ON orders(status, created_at DESC)
  WHERE status NOT IN ('delivered', 'cancelled');

-- Orders: by payment status (for reconciliation)
CREATE INDEX idx_orders_payment_status
  ON orders(payment_status) WHERE payment_status IN ('pending', 'pending_cash', 'pending_refund', 'refund_failed');

-- Orders: by idempotency key (duplicate order check)
CREATE INDEX idx_orders_idempotency
  ON orders(idempotency_key) WHERE idempotency_key IS NOT NULL;

-- Order items: by order
CREATE INDEX idx_order_items_order
  ON order_items(order_id);

-- Order status history: by order (chronological)
CREATE INDEX idx_order_status_history_order
  ON order_status_history(order_id, created_at DESC);

